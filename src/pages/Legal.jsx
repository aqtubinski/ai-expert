// Реквизит оператора или заметная пометка, если его ещё не заполнили
function F({ v, hint }) {
  return v ? <>{v}</> : <mark className="blank">укажите: {hint}</mark>
}

const Name = () => <F v={OPERATOR.name} hint="ФИО или название оператора" />
const Email = () =>
  OPERATOR.email ? <a href={`mailto:${OPERATOR.email}`}>{OPERATOR.email}</a> : <mark className="blank">укажите: почта для обращений</mark>

function EraseButton() {
  const { signOut } = useAuth()
  const erase = () => {
    if (!window.confirm('Удалить из этого браузера историю разборов, настройки, согласие и выйти из аккаунта? Вернуть данные будет нельзя.'))
      return
    eraseLocalData()
    signOut()
  }
  return (
    <button className="btn btn-small" onClick={erase}>
      Удалить мои данные из этого браузера
    </button>
  )
}

