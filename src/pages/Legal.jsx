export default function Legal() {
  const { doc } = useParams()
  const { user } = useAuth()
  const page = DOCS[doc]
  if (!page) return <Navigate to="/legal/agent" replace />

  return (
    <div className="legal">
      <header className="topbar">
        <Link to="/" className="brand">
          AI Expert
        </Link>
        <nav className="topnav" aria-label="Документы">
          {LEGAL_DOCS.map((d) => (
            <NavLink key={d.id} to={`/legal/${d.id}`}>
              {d.short}
            </NavLink>
          ))}
        </nav>
        <div className="topbar-end">
          <ThemeButton />
          <Link className="btn btn-small" to="/">
            {user ? 'К разбору ТЗ' : 'Ко входу'}
          </Link>
        </div>
      </header>

      <main className="legal-main">
        <article className="legal-doc">
          {isDraft && (
            <p className="legal-draft" role="note">
              <strong>Черновик.</strong> Текст не проверен юристом
              {OPERATOR.name ? '' : ', реквизиты оператора не заполнены'}. До проверки документ не имеет силы и
              показан для ознакомления.
            </p>
          )}
          <h1>{page.title}</h1>
          <p className="legal-rev">Редакция от {OPERATOR.revision}</p>
          {page.body}
        </article>
      </main>
    </div>
  )
}
